package Map.Ex9.entities;

public class AlunosEx12 {
    private String nome;
    private Character turma;

    public AlunosEx12(String nome, Character turma) {
        this.nome = nome;
        this.turma = turma;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public Character getTurma() {
        return turma;
    }

    public void setTurma(Character turma) {
        this.turma = turma;
    }
}
